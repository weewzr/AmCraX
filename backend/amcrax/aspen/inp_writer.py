"""Aspen Plus input-language (.inp) generator for the AmCraX flowsheets.

The Aspen model is generated from :class:`amcrax.schemas.CaseInputs` instead of being edited by
hand, so that every run is reproducible from a text file kept under version control and no original
model can be overwritten.  The generated ``.inp`` file is opened by Aspen Plus V15 through COM
(:mod:`amcrax.aspen.session`), which imports it exactly as the GUI would via *File > Open*.

Two models are generated:

``build_flowsheet_input``
    The full AmCraX flowsheet of ``config/flowsheet.json``::

        FEED -> PUMP -> VAPORIZR -> FEHE(cold) -> HEATER -> CRACKER -> FEHE(hot) -> COOLER -> PSA -> H2PROD
                                                                                PSA -> TAILGAS -> BURNER <- AIR
                                                                                BURNER -> FLUE -> FLUEHX -> STACK

``build_equilibrium_input``
    A minimal FEED -> RGibbs model used only to validate the independent Python equilibrium model.

Property method rationale (documented in the technical report): the system is a non-polar/weakly
polar light-gas mixture (H2, N2) with NH3 at 3-40 bar and up to 900 degC, i.e. the regime for which
a cubic equation of state is the standard choice; PENG-ROB is used for all sections.
"""
from __future__ import annotations

from amcrax.schemas import CaseInputs

#: Minimum reactor pressure for which the fixed pressure profile of the full flowsheet is physical
#: (PSA product leaves at P - 1.0 bar and the tail gas at 1.3 bar).
MIN_FLOWSHEET_PRESSURE_BAR = 3.0

#: Pressure offsets relative to the reactor outlet pressure, bar (see config/flowsheet.json).
DP = {
    "PUMP": +1.0,
    "VAPORIZR": +0.8,
    "FEHE_COLD_DROP": 0.3,
    "FEHE_HOT_DROP": 0.3,
    "HEATER": +0.2,
    "COOLER": -0.5,
    "H2PROD": -1.0,
}
TAILGAS_PRESSURE_BAR = 1.3
AIR_PRESSURE_BAR = 1.3
BURNER_PRESSURE_BAR = 1.2
FLUEHX_PRESSURE_BAR = 1.1
VAPORIZER_SUPERHEAT_K = 10.0
PUMP_EFFICIENCY = 0.75
FEED_PRESSURE_BAR = 1.013

_HEADER = """;
; {title}
; Generated by amcrax.aspen.inp_writer - do not edit by hand; regenerate from CaseInputs.
;
TITLE '{title}'

IN-UNITS MET PRESSURE=bar TEMPERATURE=C DELTA-T=C PDROP=bar  &
        ENTHALPY-FLO=kW POWER=kW

DEF-STREAMS CONVEN ALL

MODEL-OPTION

DESCRIPTION "
    {description}
    "

DATABANKS 'APV150 PURE41' / 'APV150 AQUEOUS' /  &
        'APV150 INORGANIC' / NOASPENPCD

PROP-SOURCES 'APV150 PURE41' / 'APV150 AQUEOUS' /  &
        'APV150 INORGANIC'

COMPONENTS
    NH3 H3N /
    H2 H2 /
    N2 N2 /
    H2O H2O /
    O2 O2

SOLVE
    RUN-MODE MODE=SIM
"""


def _f(x: float) -> str:
    """Format a number for the input language (always with a decimal point)."""
    s = f"{float(x):.10g}"
    if "e" in s or "E" in s:
        s = f"{float(x):.12f}".rstrip("0")
    if "." not in s:
        s += "."
    return s


def validate_flowsheet_inputs(inputs: CaseInputs) -> None:
    """Raise ``ValueError`` for specifications the fixed-topology flowsheet cannot represent."""
    if inputs.reactor_pressure_bar < MIN_FLOWSHEET_PRESSURE_BAR:
        raise ValueError(
            f"reactor_pressure_bar={inputs.reactor_pressure_bar} is below the minimum "
            f"{MIN_FLOWSHEET_PRESSURE_BAR} bar supported by the full flowsheet (PSA product at P-1.0 bar, "
            f"tail gas at {TAILGAS_PRESSURE_BAR} bar). Use the equilibrium model for lower pressures."
        )
    if inputs.heat_integration:
        t_cold_out = inputs.reactor_temperature_C - inputs.fehe_hot_end_approach_K
        t_min = fehe_cold_outlet_minimum_C(inputs.reactor_pressure_bar)
        if t_cold_out <= t_min:
            raise ValueError(
                f"FEHE cold outlet temperature {t_cold_out:.1f} degC is not sufficiently above the vaporiser outlet "
                f"(estimated minimum {t_min:.1f} degC at {inputs.reactor_pressure_bar:g} bar); "
                "reduce fehe_hot_end_approach_K or raise reactor_temperature_C."
            )


#: Margin above the pure-ammonia saturation temperature + vaporiser superheat required of the FEHE cold
#: outlet: about 15 K for the dew-point rise caused by the feed water (Aspen PENG-ROB gives 65.9 degC
#: against 50.9 degC for pure NH3 at 20.8 bar) plus a 10 K minimum driving force.
FEHE_GUARD_MARGIN_K = 25.0


def fehe_cold_outlet_minimum_C(reactor_pressure_bar: float) -> float:
    """Lowest admissible FEHE cold-outlet temperature at a given reactor pressure.

    The cold inlet is the vaporiser outlet (dew point + superheat), which rises with pressure, so the
    guard must be pressure dependent (a fixed 120 degC threshold was too low above about 65 bar).
    Uses the CoolProp ammonia saturation curve; falls back to the old fixed value if CoolProp is
    unavailable or the pressure is above the critical pressure.
    """
    p_pa = (reactor_pressure_bar + DP["VAPORIZR"]) * 1.0e5
    try:
        from CoolProp.CoolProp import PropsSI

        t_sat_c = float(PropsSI("T", "P", p_pa, "Q", 1, "Ammonia")) - 273.15
    except Exception:
        return 120.0
    return t_sat_c + VAPORIZER_SUPERHEAT_K + FEHE_GUARD_MARGIN_K


def build_flowsheet_input(inputs: CaseInputs, *, native_sensitivity: bool = False, kinetic_cracker=None) -> str:
    """Return the Aspen Plus input file for the full AmCraX flowsheet.

    ``native_sensitivity`` adds a calculator that ties the HEATER / FEHE temperatures to the CRACKER
    temperature and an Aspen-native Sensitivity block (reactor temperature sweep). It is used for the
    documented baseline model; parameter studies driven from Python do not need it.

    ``kinetic_cracker`` (research option, default None = unchanged RGibbs text): an
    :class:`amcrax.aspen.kinetic.KineticReactorInputs` whose catalyst, bed and geometry replace the RGibbs
    CRACKER by a catalyst-kinetic RPLUG with the same block id and streams (isothermal at the CaseInputs
    reactor temperature unless its thermal_mode says otherwise).
    """
    if kinetic_cracker is not None:
        return _build_flowsheet_with_kinetic_cracker(inputs, kinetic_cracker, native_sensitivity)
    validate_flowsheet_inputs(inputs)
    p = inputs.reactor_pressure_bar
    t = inputs.reactor_temperature_C
    hi = inputs.heat_integration
    x_h2o = inputs.feed_h2o_mole_frac
    x_nh3 = 1.0 - x_h2o

    title = f"AmCraX ammonia cracking - {inputs.case_id}"
    description = (
        "AmCraX ammonia-cracking flowsheet: refrigerated liquid NH3 is pumped, "
        "vaporised, preheated against the reactor effluent, cracked at chemical "
        "equilibrium (RGibbs), cooled and split in a reduced-order PSA block; "
        "the PSA tail gas is burned with air. Property method: "
        f"{inputs.property_method}."
    )
    out = [_HEADER.format(title=title, description=description)]

    # ---------------------------------------------------------------- flowsheet connectivity
    fs = ["FLOWSHEET", "    BLOCK PUMP IN=FEED OUT=S1", "    BLOCK VAPORIZR IN=S1 OUT=S2"]
    if hi:
        fs += [
            "    BLOCK FEHE IN=S5 S2 OUT=S6 S3",
            "    BLOCK HEATER IN=S3 OUT=S4",
            "    BLOCK CRACKER IN=S4 OUT=S5",
            "    BLOCK COOLER IN=S6 OUT=S7",
        ]
    else:
        fs += [
            "    BLOCK HEATER IN=S2 OUT=S4",
            "    BLOCK CRACKER IN=S4 OUT=S5",
            "    BLOCK COOLER IN=S5 OUT=S7",
        ]
    fs += [
        "    BLOCK PSA IN=S7 OUT=H2PROD TAILGAS",
        "    BLOCK BURNER IN=TAILGAS AIR OUT=FLUE",
        "    BLOCK FLUEHX IN=FLUE OUT=STACK",
    ]
    out.append("\n".join(fs) + "\n")

    out.append(f"PROPERTIES {inputs.property_method}\n")

    # ---------------------------------------------------------------- feed streams
    out.append(
        "STREAM FEED\n"
        f"    SUBSTREAM MIXED PRES={_f(FEED_PRESSURE_BAR)} VFRAC=0. MOLE-FLOW={_f(inputs.feed_total_kmol_h)}\n"
        f"    MOLE-FRAC NH3 {_f(x_nh3)} / H2O {_f(x_h2o)}\n"
    )
    # The AIR flow given here is only an initial value: calculator AIRCALC overwrites it.
    out.append(
        "STREAM AIR\n"
        f"    SUBSTREAM MIXED TEMP=25. PRES={_f(AIR_PRESSURE_BAR)} MOLE-FLOW={_f(inputs.feed_total_kmol_h)}\n"
        "    MOLE-FRAC N2 0.79 / O2 0.21\n"
    )

    # ---------------------------------------------------------------- unit operations
    out.append(f"BLOCK PUMP PUMP\n    PARAM PRES={_f(p + DP['PUMP'])} EFF={_f(PUMP_EFFICIENCY)}\n")
    out.append(
        f"BLOCK VAPORIZR HEATER\n    PARAM PRES={_f(p + DP['VAPORIZR'])} DEGSUP={_f(VAPORIZER_SUPERHEAT_K)}\n"
    )
    if hi:
        out.append(
            "BLOCK FEHE HEATX\n"
            f"    PARAM T-COLD={_f(t - inputs.fehe_hot_end_approach_K)} CALC-TYPE=DESIGN  &\n"
            f"        PRES-HOT={_f(-DP['FEHE_HOT_DROP'])} PRES-COLD={_f(-DP['FEHE_COLD_DROP'])}  &\n"
            "        U-OPTION=PHASE F-OPTION=CONSTANT CALC-METHOD=SHORTCUT\n"
            "    FEEDS HOT=S5 COLD=S2\n"
            "    OUTLETS-HOT S6\n"
            "    OUTLETS-COLD S3\n"
            "    HOT-SIDE DP-OPTION=CONSTANT\n"
            "    COLD-SIDE DP-OPTION=CONSTANT\n"
            "    TQ-PARAM CURVE=YES\n"
        )
    out.append(f"BLOCK HEATER HEATER\n    PARAM TEMP={_f(t)} PRES={_f(p + DP['HEATER'])}\n")
    out.append(
        "BLOCK CRACKER RGIBBS\n"
        f"    PARAM TEMP={_f(t)} PRES={_f(p)}\n"
        "    PROD NH3 / H2 / N2 / H2O\n"
    )
    out.append(
        f"BLOCK COOLER HEATER\n    PARAM TEMP={_f(inputs.psa_feed_temperature_C)} PRES={_f(p + DP['COOLER'])}\n"
    )
    out.append(
        "BLOCK PSA SEP\n"
        "    PARAM\n"
        "    FRAC STREAM=H2PROD SUBSTREAM=MIXED COMPS=NH3 H2 N2 H2O O2 FRACS=  &\n"
        f"        0. {_f(inputs.psa_h2_recovery)} {_f(inputs.psa_n2_slip)} 0. 0.\n"
        f"    FLASH-SPECS H2PROD PRES={_f(p + DP['H2PROD'])}\n"
        f"    FLASH-SPECS TAILGAS PRES={_f(TAILGAS_PRESSURE_BAR)}\n"
    )
    out.append(
        "BLOCK BURNER RSTOIC\n"
        f"    PARAM PRES={_f(BURNER_PRESSURE_BAR)} DUTY=0.\n"
        "    STOIC 1 MIXED H2 -1. / O2 -0.5 / H2O 1.\n"
        "    STOIC 2 MIXED NH3 -1. / O2 -0.75 / N2 0.5 / H2O 1.5\n"
        "    CONV 1 MIXED H2 1.\n"
        "    CONV 2 MIXED NH3 1.\n"
    )
    out.append(
        f"BLOCK FLUEHX HEATER\n    PARAM TEMP={_f(inputs.stack_temperature_C)} PRES={_f(FLUEHX_PRESSURE_BAR)}\n"
    )

    # ---------------------------------------------------------------- combustion-air calculator
    lam = 1.0 + inputs.burner_excess_air
    out.append(
        "CALCULATOR AIRCALC\n"
        "    DEFINE FH2 MOLE-FLOW STREAM=TAILGAS SUBSTREAM=MIXED  &\n"
        "        COMPONENT=H2\n"
        "    DEFINE FNH3 MOLE-FLOW STREAM=TAILGAS SUBSTREAM=MIXED  &\n"
        "        COMPONENT=NH3\n"
        "    DEFINE FAIR STREAM-VAR STREAM=AIR SUBSTREAM=MIXED  &\n"
        "        VARIABLE=MOLE-FLOW\n"
        f"F     FAIR = (0.5*FH2 + 0.75*FNH3) * {_f(lam)} / 0.21\n"
        "    READ-VARS FH2 FNH3\n"
        "    WRITE-VARS FAIR\n"
    )

    if native_sensitivity:
        tie = [
            "CALCULATOR TLINK",
            "    DEFINE TRX BLOCK-VAR BLOCK=CRACKER VARIABLE=TEMP  &",
            "        SENTENCE=PARAM",
            "    DEFINE THT BLOCK-VAR BLOCK=HEATER VARIABLE=TEMP  &",
            "        SENTENCE=PARAM",
        ]
        if hi:
            tie += [
                "    DEFINE TFE BLOCK-VAR BLOCK=FEHE VARIABLE=T-COLD  &",
                "        SENTENCE=PARAM",
            ]
        tie += ["F     THT = TRX"]
        if hi:
            tie += [f"F     TFE = TRX - {_f(inputs.fehe_hot_end_approach_K)}"]
        # READ-VARS / WRITE-VARS (not EXECUTE FIRST) so that the calculator is sequenced before
        # FEHE and HEATER and is re-executed for every Sensitivity case.
        tie += ["    READ-VARS TRX", "    WRITE-VARS THT TFE" if hi else "    WRITE-VARS THT"]
        out.append("\n".join(tie) + "\n")
        out.append(
            "SENSITIVITY STEMP\n"
            "    DEFINE NH3IN MOLE-FLOW STREAM=S4 SUBSTREAM=MIXED  &\n"
            "        COMPONENT=NH3\n"
            "    DEFINE NH3OUT MOLE-FLOW STREAM=S5 SUBSTREAM=MIXED  &\n"
            "        COMPONENT=NH3\n"
            "    DEFINE H2P MOLE-FLOW STREAM=H2PROD SUBSTREAM=MIXED  &\n"
            "        COMPONENT=H2\n"
            "    DEFINE QRX BLOCK-VAR BLOCK=CRACKER VARIABLE=QCALC  &\n"
            "        SENTENCE=PARAM\n"
            "    DEFINE QHT BLOCK-VAR BLOCK=HEATER VARIABLE=QCALC  &\n"
            "        SENTENCE=PARAM\n"
            "F     CONV = 1.0 - NH3OUT/NH3IN\n"
            '    TABULATE 1 "CONV" COL-LABEL="NH3" "CONV"\n'
            '    TABULATE 2 "H2P" COL-LABEL="H2 PROD" "KMOL/HR"\n'
            '    TABULATE 3 "QRX" COL-LABEL="CRACKER" "DUTY"\n'
            '    TABULATE 4 "QHT" COL-LABEL="HEATER" "DUTY"\n'
            "    VARY BLOCK-VAR BLOCK=CRACKER VARIABLE=TEMP SENTENCE=PARAM\n"
            '    RANGE LOWER="350" UPPER="800" INCR="50"\n'
        )

    out.append("STREAM-REPOR MOLEFLOW MASSFLOW MOLEFRAC MASSFRAC\n")
    return "\n".join(out)


def _build_flowsheet_with_kinetic_cracker(inputs: CaseInputs, kin, native_sensitivity: bool) -> str:
    """Full flowsheet text with the CRACKER RGIBBS block replaced by a kinetic RPLUG (research option)."""
    from amcrax.aspen.kinetic import any_reactions_block, resolve_spec, rplug_block

    if native_sensitivity:
        raise ValueError("native_sensitivity varies the RGibbs CRACKER TEMP and is not available with kinetic_cracker")
    base = build_flowsheet_input(inputs, native_sensitivity=False)
    t, p = inputs.reactor_temperature_C, inputs.reactor_pressure_bar
    rgibbs = (
        "BLOCK CRACKER RGIBBS\n"
        f"    PARAM TEMP={_f(t)} PRES={_f(p)}\n"
        "    PROD NH3 / H2 / N2 / H2O\n"
    )
    if base.count(rgibbs) != 1:
        raise RuntimeError("CRACKER RGIBBS block not found exactly once in the generated flowsheet text")
    spec = resolve_spec(kin.catalyst_id, kin.kinetic_form)
    text = base.replace(rgibbs, rplug_block(kin, "CRACKER", temperature_C=t))
    if spec.requires_h2_seed and kin.h2_seed_conversion > 0:
        # Rate singular at p_H2 = 0: a small gaseous H2/N2 seed stream H2SEED (3:1, equal to cracking a fraction
        # h2_seed_conversion of the fed NH3) joins the HEATER inlet. Seeding the liquid FEED instead caused
        # enthalpy-initialisation errors in FEED and changed the PUMP/vaporiser duties.
        f_nh3 = inputs.feed_total_kmol_h * (1.0 - inputs.feed_h2o_mole_frac)
        sd = kin.h2_seed_conversion * f_nh3
        heater_in = "S3" if inputs.heat_integration else "S2"
        old = f"    BLOCK HEATER IN={heater_in} OUT=S4\n"
        if text.count(old) != 1:
            raise RuntimeError("HEATER connectivity not found exactly once")
        text = text.replace(old, f"    BLOCK HEATER IN={heater_in} H2SEED OUT=S4\n")
        seed = (
            "STREAM H2SEED\n"
            f"    SUBSTREAM MIXED TEMP={_f(t)} PRES={_f(p + DP['HEATER'] + 1.0)}\n"
            f"    MOLE-FLOW H2 {_f(1.5 * sd)} / N2 {_f(0.5 * sd)}\n"
        )
        text = text.replace("STREAM AIR\n", seed + "\nSTREAM AIR\n", 1)
    text = text.replace("cracked at chemical equilibrium (RGibbs)","cracked in a catalyst-kinetic RPLUG")
    tail = "STREAM-REPOR MOLEFLOW MASSFLOW MOLEFRAC MASSFRAC\n"
    return text.replace(tail, any_reactions_block(spec) + "\n" + tail)


def build_equilibrium_input(
    temperature_C: float = 500.0,
    pressure_bar: float = 1.0,
    property_method: str = "PENG-ROB",
) -> str:
    """Minimal validation model: pure NH3 vapour at (T, P) -> isothermal RGibbs at (T, P).

    Because the feed already enters at reactor temperature, the RGibbs duty equals the heat of
    reaction absorbed at T, which is what the Python model's ``heat_duty`` is compared with.
    """
    title = "AmCraX equilibrium validation model"
    description = (
        "Pure NH3 at reactor temperature and pressure fed to an isothermal RGibbs "
        "reactor. Used only to validate the independent Python equilibrium model. "
        f"Property method: {property_method}."
    )
    body = [
        _HEADER.format(title=title, description=description),
        "FLOWSHEET\n    BLOCK REQ IN=EQFEED OUT=EQPROD\n",
        f"PROPERTIES {property_method}\n",
        "STREAM EQFEED\n"
        f"    SUBSTREAM MIXED TEMP={_f(temperature_C)} PRES={_f(pressure_bar)} MOLE-FLOW=1.\n"
        "    MOLE-FRAC NH3 1.\n",
        "BLOCK REQ RGIBBS\n"
        f"    PARAM TEMP={_f(temperature_C)} PRES={_f(pressure_bar)}\n"
        "    PROD NH3 / H2 / N2\n",
        "STREAM-REPOR MOLEFLOW MOLEFRAC\n",
    ]
    return "\n".join(body)
