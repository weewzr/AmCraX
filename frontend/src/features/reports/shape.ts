import type { FigureItem, ReportItem, TraceItem } from '../../api/reports'

export const FIGURE_GROUPS: [string, string][] = [
  ['aspen_', 'Aspen Plus sensitivity studies'], ['equilibrium_', 'Thermodynamic equilibrium'], ['hi_', 'Heat integration'],
  ['lcoh_', 'Techno-economics (LCOH)'], ['ci_', 'Carbon intensity'], ['pfr_', 'Reactor (PFR) and kinetics'], ['sep_', 'Separation'],
  ['opt_', 'Optimisation'], ['validation_', 'Validation'],
]
export interface FigureGroup { prefix: string; title: string; items: { name: string; url: string; caption: string }[] }

/** Caption derived from the file name only: prefix removed, underscores to spaces, extension dropped. */
export function captionOf(name: string): string {
  const base = name.replace(/\.[a-z0-9]+$/i, '')
  const grp = FIGURE_GROUPS.find(([p]) => base.startsWith(p))
  const s = (grp ? base.slice(grp[0].length) : base).replace(/_/g, ' ').trim()
  return s.charAt(0).toUpperCase() + s.slice(1)
}

export function groupFigures(figs: FigureItem[]): FigureGroup[] {
  const groups: FigureGroup[] = FIGURE_GROUPS.map(([prefix, title]) => ({ prefix, title, items: [] }))
  const other: FigureGroup = { prefix: '', title: 'Other', items: [] }
  for (const f of [...figs].sort((a, b) => a.name.localeCompare(b.name))) {
    const g = groups.find((x) => f.name.startsWith(x.prefix)) ?? other
    g.items.push({ name: f.name, url: f.url, caption: captionOf(f.name) })
  }
  return [...groups, other].filter((g) => g.items.length)
}

export const KIND_LABEL: Record<string, string> = {
  report: 'Report', deck: 'Pitch deck', validation: 'Validation', docs: 'Documentation', aspen_model: 'Aspen model files', research: 'Research',
}
export function groupReports(rs: ReportItem[]): { kind: string; title: string; items: ReportItem[] }[] {
  const kinds = [...new Set(rs.map((r) => r.kind))]
  return kinds.map((k) => ({ kind: k, title: KIND_LABEL[k] ?? k, items: rs.filter((r) => r.kind === k) }))
}
export const fmtBytes = (b: number | null | undefined): string =>
  b === null || b === undefined || !Number.isFinite(b) ? 'n/a' : b >= 1048576 ? `${(b / 1048576).toFixed(1)} MB` : `${Math.max(1, Math.round(b / 1024))} kB`

export const limitationsText = (t: TraceItem): string => (Array.isArray(t.limitations) ? t.limitations.join('; ') : t.limitations ?? '')

/** DOI link: explicit doi field, else the URL when it is a doi.org link, else null. */
export function doiLink(doi: string | null | undefined, url: string | null | undefined): string | null {
  if (doi) return `https://doi.org/${doi.replace(/^https?:\/\/(dx\.)?doi\.org\//, '')}`
  return url && /doi\.org/.test(url) ? url : null
}

